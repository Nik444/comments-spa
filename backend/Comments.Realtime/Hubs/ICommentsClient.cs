namespace Comments.Realtime.Hubs;

// Что сервер может вызвать у браузера. Сигналы содержат только Id, за самими комментариями клиент ходит в API.
// [разбор] Это интерфейс "в обратную сторону": не то, что браузер вызывает на сервере, а то, что сервер вызывает в браузере.
// [разбор] В JavaScript на странице на эти имена вешаются обработчики: connection.on('NewRoots', ids => ...).
// [разбор] Благодаря интерфейсу компилятор проверит имена и типы: опечатка в названии метода не соберётся.
public interface ICommentsClient
{
    // Появились новые корневые комментарии. Приходит всем, кто подключён.
    Task NewRoots(IReadOnlyList<long> ids);

    // Появились новые ответы в ветке rootId. Приходит только тем, кто подписан на эту ветку.
    Task NewReplies(long rootId, IReadOnlyList<long> ids);
}
